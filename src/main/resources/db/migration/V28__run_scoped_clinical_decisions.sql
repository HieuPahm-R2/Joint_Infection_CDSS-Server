ALTER TABLE public.doctor_final_decisions
    ADD COLUMN run_id bigint,
    ADD COLUMN author_user_id bigint,
    ADD COLUMN status character varying(20) NOT NULL DEFAULT 'DRAFT',
    ADD COLUMN signed_at timestamp with time zone,
    ADD COLUMN version_no bigint NOT NULL DEFAULT 0;

UPDATE public.doctor_final_decisions decision
SET run_id = review.run_id
FROM public.doctor_recommendation_reviews review
WHERE review.id = decision.review_id;

UPDATE public.doctor_final_decisions decision
SET author_user_id = (
    SELECT app_user.id
    FROM public.users app_user
    WHERE lower(app_user.email) = lower(decision.created_by)
    ORDER BY app_user.id
    LIMIT 1
)
WHERE decision.author_user_id IS NULL;

ALTER TABLE public.doctor_final_decisions
    ALTER COLUMN run_id SET NOT NULL,
    ADD CONSTRAINT fk_doctor_decision_run
        FOREIGN KEY (run_id) REFERENCES public.ai_recommendation_runs(id) ON DELETE CASCADE,
    ADD CONSTRAINT fk_doctor_decision_author
        FOREIGN KEY (author_user_id) REFERENCES public.users(id) ON DELETE RESTRICT,
    ADD CONSTRAINT chk_doctor_decision_status
        CHECK (status IN ('DRAFT', 'SIGNED'));

CREATE UNIQUE INDEX uq_doctor_decision_run
    ON public.doctor_final_decisions (run_id);

CREATE INDEX idx_doctor_decision_author
    ON public.doctor_final_decisions (author_user_id);

-- Preserve the meaning of a legacy final review: it was already accepted by
-- its doctor, so the migrated doctor lane must be immutable as well.
UPDATE public.doctor_final_decisions decision
SET status = 'SIGNED',
    signed_at = COALESCE(decision.signed_at, review.updated_at, review.created_at)
FROM public.doctor_recommendation_reviews review
WHERE review.id = decision.review_id
  AND review.is_final_decision = true;

CREATE TABLE public.pharmacist_final_decisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL UNIQUE
        REFERENCES public.ai_recommendation_runs(id) ON DELETE CASCADE,
    author_user_id bigint NOT NULL
        REFERENCES public.users(id) ON DELETE RESTRICT,
    status character varying(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SIGNED')),
    systemic_antibiotic_plan_json jsonb,
    local_antibiotic_plan_json jsonb,
    notes text,
    signed_at timestamp with time zone,
    version_no bigint NOT NULL DEFAULT 0,
    created_by character varying(255),
    updated_by character varying(255),
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_pharmacist_decision_author
    ON public.pharmacist_final_decisions (author_user_id);

CREATE TABLE public.recommendation_final_selections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id bigint NOT NULL UNIQUE
        REFERENCES public.pji_episodes(id) ON DELETE CASCADE,

-- V39 (decision 0010 section 2 / decision 3): vital signs as a 1:N history.
--
-- Today the four vital fields live on clinical_assessments, so each save
-- overwrites them and the clinical picture over time cannot be reconstructed --
-- which is also why the AI layer has to copy the whole record into a snapshot.
--
-- This migration creates the measurement table and backfills one row per
-- assessment that actually carries a vital. It is additive: the four columns stay
-- on clinical_assessments, so nothing that reads them changes yet. The write path
-- starts appending measurements in the same change, and a later step flips reads
-- over before the columns are dropped.

CREATE TABLE public.vital_signs_measurements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id bigint NOT NULL,
    recorded_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    blood_pressure character varying(20),
    height_cm numeric(5,2),
    weight_kg numeric(5,2),
    bmi numeric(4,2),
    version_no bigint NOT NULL DEFAULT 0,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp without time zone,
    created_by character varying(255),
    updated_by character varying(255),
    CONSTRAINT vital_signs_measurements_admission_id_fkey
        FOREIGN KEY (admission_id) REFERENCES public.admissions(id) ON DELETE CASCADE
);

CREATE INDEX idx_vital_signs_measurements_admission_recorded
    ON public.vital_signs_measurements (admission_id, recorded_at DESC);

-- Backfill: the current values of each assessment become its first measurement,
-- timestamped when the assessment was written. Recorded as a migration so the
-- history does not start empty.
INSERT INTO public.vital_signs_measurements
    (admission_id, recorded_at, blood_pressure, height_cm, weight_kg, bmi,
     version_no, created_at, created_by)
SELECT assessment.admission_id,
       COALESCE(assessment.created_at, CURRENT_TIMESTAMP),
       assessment.blood_pressure,
       assessment.height_cm,
       assessment.weight_kg,
       assessment.bmi,
       0,
       COALESCE(assessment.created_at, CURRENT_TIMESTAMP),
       'migration:V39'
  FROM public.clinical_assessments assessment
 WHERE assessment.blood_pressure IS NOT NULL
    OR assessment.height_cm IS NOT NULL
    OR assessment.weight_kg IS NOT NULL
    OR assessment.bmi IS NOT NULL;

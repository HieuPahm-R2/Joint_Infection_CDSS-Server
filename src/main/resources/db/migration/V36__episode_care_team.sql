-- V36__episode_care_team.sql
--
-- Episode care-team membership: the record-relationship layer of the
-- deny-by-default authorization policy.
--
-- docs/decisions/0008-general-authorization-policy.md requires that access to a
-- clinical record needs ownership OR explicit care-team membership for its
-- episode. Until now only ownership existed, expressed as the free-text
-- pji_episodes.created_by / patients.created_by email columns, and the checks
-- that read them failed OPEN when that text was blank. This table gives the
-- relationship a real, grantable, revocable representation.
--
-- Three properties matter:
--
--   1. created_by is free text that AbstractEntity writes as the literal ' '
--      when there is no principal (model/AbstractEntity.java handleBeforeCreate),
--      so ownership-over-email is unresolvable for those rows. Membership here is
--      a real user FK and cannot be blank.
--   2. A pharmacist needs access to an episode they did not create. Previously
--      the only way to express that was a blanket "any pharmacist may act on any
--      episode" exemption, which is the privilege bypass this table replaces.
--   3. The backfill below enrolls every episode creator who resolves to a real
--      ACTIVE user account. Episodes whose creator cannot be resolved stay
--      admin-only until an administrator assigns a member explicitly, which is
--      the transition promised in docs/plans/active/authorization-hardening.md.

CREATE TABLE "public"."episode_care_team" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "episode_id" bigint NOT NULL,
    "user_id" bigint NOT NULL,
    -- OWNER | DOCTOR | PHARMACIST | NURSE. Plain varchar on purpose: the membership
    -- role is authorization metadata for this table, not a clinical enum, and the
    -- service validates it. (users.status is likewise varchar even though a
    -- userstatus type exists - see V35__backfill_user_status_active.sql.)
    "member_role" character varying(32) NOT NULL,
    -- Soft removal. A revoked membership must stop granting access without
    -- destroying the record of who was once responsible for the episode.
    "active" boolean DEFAULT true NOT NULL,
    "created_at" timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "updated_at" timestamp without time zone,
    "created_by" character varying(255),
    "updated_by" character varying(255),
    CONSTRAINT "episode_care_team_episode_id_fkey"
        FOREIGN KEY ("episode_id") REFERENCES "public"."pji_episodes"("id") ON DELETE CASCADE,
    CONSTRAINT "episode_care_team_user_id_fkey"
        FOREIGN KEY ("user_id") REFERENCES "public"."users"("id") ON DELETE CASCADE
);

-- One membership row per (episode, user). Re-granting reactivates the row instead
-- of inserting a duplicate, so the authorization lookup is a plain existence test.
CREATE UNIQUE INDEX "uq_episode_care_team_episode_user"
    ON "public"."episode_care_team" ("episode_id", "user_id");

-- Access check and membership listing both read active rows by episode.
CREATE INDEX "idx_episode_care_team_episode_active"
    ON "public"."episode_care_team" ("episode_id", "active");

-- "Which episodes may this user reach?" - the reverse lookup.
CREATE INDEX "idx_episode_care_team_user_active"
    ON "public"."episode_care_team" ("user_id", "active");

-- At most one active OWNER per episode. Deliberately partial (WHERE active) so a
-- revoked owner row does not block appointing a replacement.
CREATE UNIQUE INDEX "uq_episode_care_team_active_owner"
    ON "public"."episode_care_team" ("episode_id")
    WHERE "active" AND "member_role" = 'OWNER';

-- Backfill: enroll each episode's creator as its OWNER.
--
-- btrim() because AbstractEntity writes ' ' when there is no principal, and
-- lower() because the ownership comparison has always been case-insensitive
-- (RecommendationAccessService.sameUser). The join is on the users.email lookup,
-- so a creator that resolves to zero or to several accounts is simply left out
-- and the episode stays admin-only.
INSERT INTO "public"."episode_care_team" ("episode_id", "user_id", "member_role", "active", "created_by")
SELECT e."id", u."id", 'OWNER', true, 'migration:V36'
FROM "public"."pji_episodes" e
JOIN "public"."users" u ON lower(btrim(u."email")) = lower(btrim(e."created_by"))
WHERE btrim(coalesce(e."created_by", '')) <> ''
ON CONFLICT ("episode_id", "user_id") DO NOTHING;
